'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { git, repository, resolveCommit, refs, changes } = require('../src/git');
test('compare entire project from a nested directory against immutable branch/tag/commit, including unusual filenames', async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'folder-compare-'));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  await git(root, ['init']);
  await git(root, ['config', 'user.email', 'test@example.com']);
  await git(root, ['config', 'user.name', 'Test']);
  const folder = path.join(root, 'folder [x]');
  await fs.mkdir(folder);
  for (const name of ['modified.txt', 'deleted.txt', 'staged.txt', '换行\n file.txt']) await fs.writeFile(path.join(folder, name), 'before\n');
  await fs.writeFile(path.join(root, 'outside.txt'), 'before\n');
  await git(root, ['add', '.']);
  await git(root, ['commit', '-m', 'base']);
  await git(root, ['tag', 'base']);
  const commit = await resolveCommit(root, 'refs/tags/base');
  assert.equal(await resolveCommit(root, commit.slice(0, 8)), commit);
  assert.equal(await repository(folder), await fs.realpath(root));
  assert.ok((await refs(root)).some(ref => ref.ref === 'refs/tags/base'));
  await fs.writeFile(path.join(folder, 'modified.txt'), 'after\n');
  await fs.writeFile(path.join(folder, 'staged.txt'), 'staged\n');
  await git(root, ['add', '.']);
  await fs.unlink(path.join(folder, 'deleted.txt'));
  await fs.writeFile(path.join(folder, '换行\n file.txt'), 'after\n');
  await fs.writeFile(path.join(folder, 'untracked.txt'), 'new\n');
  await fs.writeFile(path.join(root, 'outside.txt'), 'after\n');
  await fs.writeFile(path.join(root, 'outside-untracked.txt'), 'new\n');
  const files = await changes(await repository(folder), commit);
  assert.equal(files.length, 7);
  const statuses = Object.fromEntries(files.map(file => [path.basename(file.path), file.status]));
  assert.deepEqual(statuses, { 'outside.txt': 'M', 'outside-untracked.txt': '?', 'deleted.txt': 'D', 'modified.txt': 'M', 'staged.txt': 'M', 'untracked.txt': '?', '换行\n file.txt': 'M' });
  const scoped = await changes(root, commit, folder);
  assert.equal(scoped.length, 5);
  assert.ok(scoped.every(file => file.path.startsWith('folder [x]/')));
  await assert.rejects(resolveCommit(root, '--help'));
  assert.equal(await git(root, ['show', `${commit}:folder [x]/modified.txt`]), 'before\n');
});
